interface I18nStore {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string, params?: Record<string, string | number>, fallback?: string) => string;
}

function readSavedLanguage(): Language {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (saved === "zh" || saved === "en") return saved;
  } catch {
    // localStorage 不可用时回退到默认中文
  }
  return "zh";
}

function interpolate(text: string, params?: Record<string, string | number>): string {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in params ? String(params[key]) : match
  );
}

export const useI18n = create<I18nStore>((set, get) => ({
  language: readSavedLanguage(),
  setLanguage: (lang) => {
    set({ language: lang });
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    } catch {
      // 忽略存储失败
    }
    // 同步页面语言标记，并重建原生菜单，保证界面与菜单文案一致
    document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
    invoke("rebuild_menu", { lang }).catch(() => {});
    // 通知 Monaco 编辑器更新上下文菜单 Action 标签
    window.dispatchEvent(new Event("markpt:lang-changed"));
  },
  t: (key, params, fallback) => {
    const { language } = get();
    const allParams = { mod: MOD_KEY, ...params };
    const entry = translations[key];
    if (!entry) return interpolate(fallback ?? key, allParams);
    return interpolate(entry[language] || entry.zh || fallback || key, allParams);
  },
}));

/** 应用启动时同步一次语言标记与原生菜单（避免重启后菜单语言与界面不一致）。 */
export function initI18n(): void {
  const { language } = useI18n.getState();
  document.documentElement.lang = language === "en" ? "en" : "zh-CN";
  invoke("rebuild_menu", { lang: language }).catch(() => {});
}
